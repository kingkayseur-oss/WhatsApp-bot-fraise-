function applyDirectMap(text, mapStr) {
  return text.split("").map((c) => {
    const lowerIdx = base.indexOf(c);
    const upperIdx = BASE.indexOf(c);
    if (lowerIdx !== -1) return mapStr.slice(0, 26)[lowerIdx] || c;
    if (upperIdx !== -1) return mapStr.slice(26, 52)[upperIdx] || c;
    return c;
  });
}

function getText(msg, args) {
  const quoted = msg.message?.extendedTextMessage?.contextInfo?.quotedMessage;
  const quotedText = quoted?.conversation || quoted?.extendedTextMessage?.text;
  return args.join(" ") || quotedText || "";
}

const directMapNames = Object.keys(maps); // 14 styles
const specialNames = Object.keys(special); // 16 styles (dont 2 alias)

const directCommands = directMapNames.map((name) => ({
  name,
  async execute(sock, msg, args) {
    const text = getText(msg, args);
    if (!text) return sock.sendMessage(msg.key.remoteJid, { text: "❌ Donne un texte." }, { quoted: msg });
    await sock.sendMessage(msg.key.remoteJid, { text: applyDirectMap(text, maps[name]).join("") }, { quoted: msg });
  },
}));

const specialCommands = specialNames.map((name) => ({
  name,
  async execute(sock, msg, args) {
    const text = getText(msg, args);
    if (!text) return sock.sendMessage(msg.key.remoteJid, { text: "❌ Donne un texte." }, { quoted: msg });
    const fn = name === "boldscript" ? (t) => applyDirectMap(t, maps.script).join("") : name === "serifbold" ? (t) => applyDirectMap(t, maps.bold).join("") : special[name];
    await sock.sendMessage(msg.key.remoteJid, { text: fn(text) }, { quoted: msg });
  },
}));

module.exports = [...directCommands, ...specialCommands];
